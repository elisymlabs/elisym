export const DEFAULT_LANGUAGE = 'en';

/**
 * The widget's texts in its current language: one object for the page, filled by
 * `applyLanguage`. Code that renders reads it at render time, so a change of language shows
 * on everything drawn after it.
 */
export const STRINGS: Strings = { ...EN };

/** The two-letter code of a BCP 47 tag the widget speaks ("pt-BR" is pt), or none. */
export function supportedLanguage(tag: string | null | undefined): string | undefined {
  const primary = tag?.trim().toLowerCase().split(/[-_]/u)[0];
  return primary !== undefined && primary !== '' && Object.hasOwn(LANGUAGES, primary)
    ? primary
    : undefined;
}

/** The first of `candidates` the widget speaks, in order of precedence, or English. */
export function resolveLanguage(candidates: ReadonlyArray<string | null | undefined>): string {
  for (const candidate of candidates) {
    const language = supportedLanguage(candidate);
    if (language !== undefined) {
      return language;
    }
  }
  return DEFAULT_LANGUAGE;
}

/** Switch every text to `language` (a code `resolveLanguage` returned). */
export function applyLanguage(language: string): void {
  Object.assign(STRINGS, LANGUAGES[language] ?? EN);
}
